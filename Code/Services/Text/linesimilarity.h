#ifndef LQCOMPARE_LINESIMILARITY_H
#define LQCOMPARE_LINESIMILARITY_H

#include "textdiff.h"

#include <QString>
#include <QVector>

namespace LqCompare { namespace Text {

// -----------------------------------------------------------------------------
// 相似度分值与「相似行对齐」（TXT-005）
// -----------------------------------------------------------------------------
//
// 为什么单独一个文件而不是塞进 `textdiff.cpp`：这里的每一件东西（分值、阈值判定、
// 单调配对、工作量上限）都是**纯函数**，输入是两行文本或两段行，输出是数或下标对。
// 它们与「Myers 怎么走」毫无关系——把 `Change::Replace` 拆成「配对的修改」与
// 「未配对的删除/新增」是**对齐之后**的一步后处理。分开之后，`Tests/Similarity`
// 可以只盯这一步（它不需要构造任何对抗性输入），而 `Tests/Text` 里那批
// 「Myers 区块边界」的用例不必跟着一起被重新验证。
//
// 术语：本模块里「相似」是**行与行的**属性（两行文本算出一个 0–100 的分值），
// 「配对」是把一对相似的行认定成「修改」而不是「一删一增」。

/// 阈值的上界，也是分值的上界（规格写的是「相似度阈值可配置（0–100）」）。
constexpr int MaximumSimilarity = 100;

///
/// \brief 「相似行对齐」阈值的出厂值（百分比）。
///
/// 定义**只有一处**：它就是 `CompareOptions::similarityThreshold` 的默认值。
/// 另写一个 50 出来，就会出现两份事实来源，而「默认值是多少」这个问题的两个答案
/// 在界面、命令行与文档里各说各话——这类分歧没有任何运行期现象。
///
int defaultSimilarityThreshold();

///
/// \brief 阈值的合法区间钳制。
///
/// 阈值来自会话文件、设置仓库与命令行，都是**整数**，因此必然会出现落在 0–100
/// 之外的值。钳制方向取「两端都钳」而不是「落在外面就退回默认值」：
/// 退回默认值会让一个手改坏的会话文件把用户**看得见**的阈值改成一个他没设过的数，
/// 而钳制只是把它压到边界——边界是用户能理解的东西（「最小 0、最大 100」）。
///
int clampSimilarityThreshold(int threshold);

///
/// \brief 一对候选行的相似度分值（0–100，整数）。
///
/// 定义为 `2·LCS / (len左 + len右)` 的百分点（LCS = 最长公共子序列长度）。
/// 选它而不是「编辑距离」或「公共前缀长度」的理由：
///
///   * 分子用 LCS 而不是「相同字符个数」，于是**顺序**被计入——`abc` 与 `cba`
///     不该拿满分，而按字符集合算它们会。
///   * 分母用两行长度之和（Dice 系数），于是「短行被长行包含」不会自动满分：
///     `int x;` 与 `int x; // 一整段很长的注释` 只有 2·7/(7+30) ≈ 38%。
///     这是刻意的——只差一个尾注的行按编辑距离几乎相同，但按「是不是同一个修改」
///     更像一改一加，而在阈值可调的前提下宁可从紧。
///   * 值域天然落在 0–100，不需要再定一个上界（`2·LCS ≤ len左 + len右`，
///     因为 `LCS ≤ min(len左, len右) ≤ (len左 + len右)/2`）。
///
/// **两侧都过 `normalizedLine()` 再算**，所以 `options` 里的忽略规则在这里同样生效：
/// 开了「忽略大小写」之后 `HELLO world` 与 `hello world` 的分值必须是 100，
/// 否则一个纯粹的大小写差异会被判成「不够相似」，于是开了忽略大小写反而更不像。
///
int lineSimilarityPercent(const QString &left, const QString &right,
                          const CompareOptions &options = CompareOptions());

///
/// \brief 阈值判定：`分值 >= 阈值` 才算相似。
///
/// 边界取「含等号」——阈值的含义是「至少这么像」。不取等号的话，
/// 阈值的**字面值**（50）与它实际放行的最低分值（51）不一致，
/// 而用户在界面上填的就是那个字面值。
///
bool isSimilarEnough(int similarityPercent, int threshold);

/// 一对配好的行（下标是**相对区间起点**的偏移，不是行号）。
struct SimilarityPair
{
    int left = 0;
    int right = 0;
};

struct SimilarityPlan
{
    /// 按左右下标分别严格递增的顺序排列。
    QVector<SimilarityPair> pairs;
    /// 工作量超过上限，**退回按位配对**（配对结果为空，由调用方决定怎么退）。
    /// 这件事必须能被调用方看见：静默退回会让「阈值调了没反应」无从归因。
    bool limited = false;
};

///
/// \brief 相似度配对的**单元格**上限（左行数 × 右行数）。
///
/// 为什么需要它：配对用的动态规划是 O(左行数 × 右行数) 的，而调用它的地方
/// 是「对齐引擎刚判定出的一段非相同区间」——那一段在对抗性输入上可以是整份文件
/// （`Tests/Text` 里那份一万行互不相关的语料就是），于是 n·m 可达 10^8 格。
///
/// 512×512 的取法：真实文件里「一段连续的改动」通常远小于这个数（源码里
/// 一次重构改几百行已经很大了），而 512 的天花板保证了配对矩阵的内存只有几 MB。
/// 超过它时**退回按位配对**——也就是这个功能出现之前的旧行为，
/// 因此退回是「少了一个新功能」，不是「结果变错」。
///
int similarityPairingMaximumCells();

///
/// \brief 相似度配对的**字符工作量**预算（左侧字符总数 × 右侧字符总数）。
///
/// 单元格上限管不住行本身很长的情况：512×512 格配上每行 500 字符，
/// 光是算分值就是 512·512·500·500 ≈ 6.5×10^10 次比较。这里的预算卡的正是这个乘积
/// ——它恰好等于「把每一对行都算一遍 LCS」的 DP 单元格总数，
/// 于是「要不要做」是一个**开跑之前就能算出来**的判断，不需要边跑边数。
///
/// 与 `AlignmentBuilder::budget` 同一个定位：把「看起来卡死了」变成一个
/// 有确定上限、可以事先拒绝的工作量。
///
qint64 similarityPairingBudget();

///
/// \brief 在两侧的一段行之间做单调的相似度配对。
///
/// 返回的配对满足：左右下标**各自严格递增**（保序，不会交叉），每对的分值都
/// `>= threshold`，且没有任何一对是「强行配对」的（低于阈值的一律不配）。
///
/// 目标函数是**字典序**的两项：先最大化配对数、再最大化总分值。
/// 先说为什么把「配对数」放第一位：规格里这个功能的目的是「把相似的行配成一对
/// （修改块）而不是两条独立增删」，也就是**能配就配**；只在配对数相同时才比总分值，
/// 用来在「左 1 行可以配右 1 行或右 2 行、都够像」时挑更像的那一对。
/// 反过来（先比总分值）会让「一对 90 分」压过「两对 60 分」，
/// 于是用户看到两行改动被缩成一处。
///
/// `budgetExceeded`（可空）回答「这次是不是因为超过上限而根本没算」——
/// 它与「算完了但一对都没配上」是两件事，混在一起就没法判断阈值改小了
/// 为什么还是老样子。
///
SimilarityPlan pairSimilarLines(const QVector<Line> &left, int leftStart, int leftCount,
                                const QVector<Line> &right, int rightStart, int rightCount,
                                const CompareOptions &options, int threshold);

} }
#endif
